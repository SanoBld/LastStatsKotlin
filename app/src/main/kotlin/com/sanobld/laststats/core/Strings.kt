private fun s(@StringRes id: Int): String = LocaleManager.context.getString(id)

private fun fmt(@StringRes id: Int, vararg args: Any?): String =
    LocaleManager.context.getString(id, *args)

private fun arr(@ArrayRes id: Int): List<String> =
    LocaleManager.context.resources.getStringArray(id).toList()

private val txIds = ConcurrentHashMap<String, Int>()
private val lfmKeep = Regex(
    "^(svc_|lfm_|faq_lfm_|faq_lb_|conn_|sw_|key_|img_src_lastfm|ui_to_last_fm|ui_view_on_last_fm|" +
        "ui_source_last_fm|ui_original_text|wl_|about_legal_marks|acct_switch)"
)

/** Keyed UI string with optional {name} arguments. Falls back to the key itself. */
fun tx(key: String, args: Map<String, String>? = null): String {
    val ctx = LocaleManager.context
    val id = txIds.getOrPut(key) {
        ctx.resources.getIdentifier("tx_" + key.lowercase().replace(Regex("[^a-z0-9_]"), "_"), "string", ctx.packageName)
    }
    var out = if (id == 0) key else ctx.getString(id)
    if (DataSource.lb && out.contains("Last.fm") && !lfmKeep.containsMatchIn(key)) {
        out = out.replace("Last.fm", "ListenBrainz")
    }
    args?.forEach { (k, v) -> out = out.replace("{$k}", v) }
    return out
}

